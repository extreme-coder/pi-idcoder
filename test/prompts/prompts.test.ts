/** Generated by calling the original Python prompt functions with the same inputs. */
const golden = JSON.parse(
	readFileSync(new URL("../fixtures/reference/prompts.json", import.meta.url), "utf8"),
) as Record<string, string>;
const rq = "What frustrates players?";

describe("pipeline prompts match the Python originals byte for byte", () => {
	it.each([
		["open_coding", () => openCodingPrompt(rq, "The game lags.")],
		["open_coding_feedback", () => openCodingPrompt(rq, "The game lags.", "FAIL\n- vague")],
		["validate", () => validateOpenCodesPrompt(rq, "The game lags.", "- Code: lag")],
		["llm_clustering", () => llmClusteringPrompt(rq)],
		["llm_clustering_empty", () => llmClusteringPrompt("  ")],
		["high_level", () => highLevelCodeGenerationPrompt("- a\n- b", rq)],
		["high_level_no_rq", () => highLevelCodeGenerationPrompt("- a", "")],
		["synthesis", () => highLevelSynthesisPrompt(["L1", "L2"], rq)],
		["refine", () => refineClusterAssignmentsPrompt("Lag", "- a\n- b", "Price, Story")],
		["meta", () => metaThemeGroupingPrompt('{"0": "Lag"}', rq)],
		["subtheme", () => intraClusterSubthemePrompt("Lag", "- a\n- b", rq)],
		["bucket", () => hierarchyRefineBucketPrompt("Lag", "Bucket", "- a", rq, 3)],
		["report", () => researchReportPrompt(rq, "GRAPH")],
		["assign", () => assignCodesToSubthemesPrompt("Lag", ["S1", "S2"], ["a", "b"], rq)],
		["codebook_single", () => codebookEnrichmentPrompt("Lag", "LC001, LC002", "- [LC001] a")],
		["codebook_batch", () => codebookBatchEnrichmentPrompt("Lag", "LC001", "- [LC001] a")],
		[
			"codebook_synthesis",
			() =>
				codebookSynthesisPrompt(
					"Lag",
					"LC001, LC002",
					2,
					"- [LC001] a\n- [LC002] b",
					20,
					"\n[Batch 1/1]\nDefinition notes: x\n",
				),
		],
		["codebook_retry_suffix", () => invalidIdsCorrection(["LC010", "LC009"], "LC001, LC002")],
		[
			"dimension_sampled",
			() => dimensionEnrichmentPrompt("Dim", "CL00, CL01", "CL00, CL01, CL02", '- [CL00]\n  [QUOTE] "q"'),
		],
		[
			"dimension_full",
			() =>
				dimensionEnrichmentPrompt(
					"Dim",
					"CL00, CL01",
					"CL00, CL01, CL02",
					'- [CL00]\n  [QUOTE] "q"',
					'- [CL02]\n  [QUOTE] "n"',
				),
		],
		["dimension_retry", () => `BASE${dimensionIdsCorrection(["CL10", "CL09"], "CL00, CL01", "CL00, CL01, CL02")}`],
	])("%s", (key, build) => {
		expect(build()).toBe(golden[key]);
	});

	it("meta-theme reminder states the bounds", () => {
		expect(metaThemeCountReminder(3, 7)).toContain("between 3 and 7 meta_themes");
	});
});

describe("evaluation prompts", () => {
	it.each([
		["recode_system_full", () => recodeSystemPrompt("full", false)],
		["recode_system_theme_only_reasoning", () => recodeSystemPrompt("theme_only", true)],
		["recode_user_full", () => recodeUserPrompt("[A] LABEL: X", '1. "q"', "full", false)],
		["recode_user_def_reasoning", () => recodeUserPrompt("[A] LABEL: X", '1. "q"', "theme_def", true)],
		["judge_system", () => judgeSystemPrompt("binary")],
		[
			"judge_user",
			() =>
				judgeUserPrompt(
					[
						{
							quote: "q1",
							optionA: { label: "A", definition: "dA", inclusion: ["i1"], exclusion: [] },
							optionB: { label: "B", definition: "dB", inclusion: [], exclusion: ["e1"] },
						},
					],
					"binary",
				),
		],
	])("%s matches Python", (key, build) => {
		expect(build()).toBe(golden[key]);
	});

	it("four-way judging offers both and neither", () => {
		expect(judgeSystemPrompt("four_way")).toMatch(/"BOTH"[\s\S]*"NEITHER"/);
		const user = judgeUserPrompt(
			[
				{
					quote: "q",
					optionA: { label: "A", definition: "", inclusion: [], exclusion: [] },
					optionB: { label: "B", definition: "", inclusion: [], exclusion: [] },
				},
			],
			"four_way",
		);
		expect(user).toContain('"A", "B", "BOTH", or "NEITHER"');
		expect(user).not.toContain("INCLUSION CRITERIA");
	});

	it("never claims criteria that are not shown", () => {
		expect(recodeSystemPrompt("theme_only", false)).not.toContain("DEFINITION");
		expect(recodeSystemPrompt("theme_def", false)).not.toContain("INCLUSION");
	});
});
